"""Characterization tests for kcwidrp.core.geometric (task T.3).

Source of every expected value: points are generated by a polynomial that the
test writes down, so the fit has an exactly known answer.

The coefficient layout of ``params`` is taken from the class docstring:
X = sum_j sum_i a_ji x**(j-i) y**i, with j the total degree and the terms
ordered 1, x, y, x^2, xy, y^2, x^3, x^2y, xy^2, y^3, ...
"""
import numpy as np
import numpy.testing as npt
import pytest

from kcwidrp.core.geometric import (AsymmetricPolynomialTransform,
                                    estimate_transform)

# Source points: 7 x 7 grid with non-zero coordinates (the estimator scales by
# the median of |x| and |y|, so a median of zero is outside its domain).
_XS, _YS = np.meshgrid(np.arange(1.0, 8.0), np.arange(2.0, 9.0))
SRC = np.column_stack([_XS.ravel(), _YS.ravel()])
X, Y = SRC.T

# Tolerance used by the fits below: the estimator forms inv(W^T W) explicitly
# for 49 points (normal equations square the condition number), measured
# worst error over these fits is ~1e-9 in float64; 1e-7 absolute leaves a
# margin of ~100 without hiding a wrong coefficient (smallest tested: 2e-3).
FIT_ATOL = 1e-7


def test_default_transform_is_identity():
    # source: analytic - default params [[0,1,0],[0,0,1]] mean X = x, Y = y
    tform = AsymmetricPolynomialTransform()
    out = tform(SRC)
    assert np.array_equal(out, SRC)


def test_explicit_params_are_applied():
    # source: analytic - X = 2 + 3x - y, Y = -1 + 0.5x + 4y evaluated by hand
    # at (1, 2): X = 2 + 3 - 2 = 3 ; Y = -1 + 0.5 + 8 = 7.5
    # at (4, -1): X = 2 + 12 + 1 = 15 ; Y = -1 + 2 - 4 = -3
    params = np.array([[2.0, 3.0, -1.0], [-1.0, 0.5, 4.0]])
    tform = AsymmetricPolynomialTransform(params)
    out = tform(np.array([[1.0, 2.0], [4.0, -1.0]]))
    assert np.array_equal(out, np.array([[3.0, 7.5], [15.0, -3.0]]))


def test_params_with_wrong_first_axis_rejected():
    # source: analytic - the class documents params as shape (2, N)
    with pytest.raises(ValueError):
        AsymmetricPolynomialTransform(np.zeros((3, 3)))


def test_inverse_is_not_available():
    # source: analytic - the docstring/message says no explicit inverse exists
    with pytest.raises(Exception, match="no explicit way"):
        AsymmetricPolynomialTransform().inverse(SRC)


def test_unknown_transform_type_rejected():
    # source: analytic - only 'asympolynomial' is registered
    with pytest.raises(ValueError):
        estimate_transform("affine", SRC, SRC)


def test_fit_recovers_known_quadratic_coefficients():
    # source: analytic - points generated from
    #   X = 3 + 1.2x + 0.05y + 0.01x^2 + 0.002xy
    #   Y = -2 + 0.03x + 0.9y + 0.004y^2
    # The fit of the same polynomial family must return those coefficients in
    # slots 0..5 (1, x, y, x^2, xy, y^2) and zero in the higher-order slots.
    dst = np.column_stack([3 + 1.2 * X + 0.05 * Y + 0.01 * X**2 + 0.002 * X * Y,
                           -2 + 0.03 * X + 0.9 * Y + 0.004 * Y**2])
    tform = estimate_transform("asympolynomial", SRC, dst)
    expect_x = np.zeros(15)
    expect_x[:6] = [3.0, 1.2, 0.05, 0.01, 0.002, 0.0]
    expect_y = np.zeros(15)
    expect_y[:6] = [-2.0, 0.03, 0.9, 0.0, 0.0, 0.004]
    assert tform.params.shape == (2, 15)
    npt.assert_allclose(tform.params[0], expect_x, rtol=0, atol=FIT_ATOL)
    npt.assert_allclose(tform.params[1], expect_y, rtol=0, atol=FIT_ATOL)


def test_fit_reproduces_destination_points():
    # source: analytic - the fitted transform applied to the source points must
    # give back the destination points the polynomial generated.
    dst = np.column_stack([3 + 1.2 * X + 0.05 * Y + 0.01 * X**2 + 0.002 * X * Y,
                           -2 + 0.03 * X + 0.9 * Y + 0.004 * Y**2])
    tform = estimate_transform("asympolynomial", SRC, dst)
    npt.assert_allclose(tform(SRC), dst, rtol=0, atol=FIT_ATOL)
    npt.assert_allclose(tform.residuals(SRC, dst), 0.0, rtol=0, atol=FIT_ATOL)


def test_order_is_x_order_then_y_order():
    # source: analytic - docstring: order = (x degree, y degree).
    # X = 1 + 2x + 0.1 y^3 is degree 1 in x and 3 in y; Y = 5 + 0.5y.
    # Slot 9 is the y^3 term (degree-3 block starts at slot 6: x^3, x^2y, xy^2,
    # y^3).
    dst = np.column_stack([1 + 2 * X + 0.1 * Y**3, 5 + 0.5 * Y])
    tform = estimate_transform("asympolynomial", SRC, dst, order=(1, 3))
    npt.assert_allclose(tform(SRC), dst, rtol=0, atol=FIT_ATOL)
    expect_x = np.zeros(15)
    expect_x[[0, 1, 9]] = [1.0, 2.0, 0.1]
    npt.assert_allclose(tform.params[0], expect_x, rtol=0, atol=FIT_ATOL)
    # Swapped orders cannot represent a y^3 term, so the fit must be poor.
    wrong = estimate_transform("asympolynomial", SRC, dst, order=(3, 1))
    assert np.abs(wrong(SRC) - dst).max() > 1.0


def test_integer_order_means_same_order_in_both_axes():
    # source: analytic - estimate() docstring code: an int order n is (n, n).
    dst = np.column_stack([1 + 2 * X + 0.1 * Y**2, 5 + 0.5 * Y + 0.01 * X * Y])
    a = estimate_transform("asympolynomial", SRC, dst, order=2)
    b = estimate_transform("asympolynomial", SRC, dst, order=(2, 2))
    assert np.array_equal(a.params, b.params)


def test_affine_inverse_round_trip():
    # source: analytic - an affine map (rotation by 30 deg, scale 1.5, shift)
    # is exactly representable.  The explicit inverse does not exist, so the
    # inverse is estimated by swapping src and dst (as the exception message
    # instructs); applying it to forward-mapped points must return the source.
    th = np.deg2rad(30.0)
    c, s = 1.5 * np.cos(th), 1.5 * np.sin(th)
    dst = np.column_stack([c * X - s * Y + 10.0, s * X + c * Y - 4.0])
    fwd = estimate_transform("asympolynomial", SRC, dst, order=1)
    inv = estimate_transform("asympolynomial", dst, SRC, order=1)
    npt.assert_allclose(fwd(SRC), dst, rtol=0, atol=FIT_ATOL)
    npt.assert_allclose(inv(fwd(SRC)), SRC, rtol=0, atol=FIT_ATOL)
